// Builds PMP.THEORY in index.html from the chapter files in this folder.
//
//   node theory/build.mjs            rewrite the block between the THEORY markers
//   node theory/build.mjs --check    exit 1 if index.html is out of date
//
// A chapter file starts with "key: value" lines (id, part, title, summary,
// why), then "## " sections. In a section, a blank line separates blocks:
// a paragraph, a list ("- " lines), a box ("> exam: ", "> myth: ",
// "> example: ") or a figure ("[figure: name]", from figures.json). The
// sections "Key ideas" and "Further reading" become the chapter's summary
// lists. **bold** and *italic* are kept as written; the app renders them.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(dir, "..");
const html = path.join(root, "index.html");
const figures = JSON.parse(fs.readFileSync(path.join(dir, "figures.json"), "utf8"));
const parts = JSON.parse(fs.readFileSync(path.join(dir, "parts.json"), "utf8"));
const WPM = 220;

function fail(file, msg) { throw new Error(`${file}: ${msg}`); }

function chapter(file) {
  const text = fs.readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n");
  const [head, ...rest] = text.split(/\n(?=## )/);
  const meta = {};
  head.split("\n").forEach((ln) => {
    const m = /^(\w+): (.*)$/.exec(ln);
    if (m) meta[m[1]] = m[2].trim();
  });
  ["id", "part", "title", "summary", "why"].forEach((k) => { if (!meta[k]) fail(file, `missing ${k}`); });
  const out = { id: meta.id, part: +meta.part, title: meta.title, summary: meta.summary, why: meta.why,
    sections: [], keyIdeas: [], reading: [] };
  let words = meta.why.split(/\s+/).length;
  rest.forEach((chunk, si) => {
    const lines = chunk.split("\n");
    const title = lines[0].replace(/^## /, "").trim();
    const blocks = [];
    lines.slice(1).join("\n").split(/\n\s*\n/).map((b) => b.trim()).filter(Boolean).forEach((b) => {
      if (/^- /.test(b)) {
        const items = b.split("\n").map((l) => l.replace(/^- /, "").trim());
        if (items.some((i) => !i)) fail(file, `empty list item in "${title}"`);
        blocks.push({ ul: items });
      } else if (/^> (exam|myth|example): /.test(b)) {
        const m = /^> (exam|myth|example): ([\s\S]*)$/.exec(b);
        blocks.push({ box: m[1], text: m[2].replace(/\n> ?/g, " ").trim() });
      } else if (/^\[figure: [\w-]+\]$/.test(b)) {
        const name = b.slice(9, -1);
        if (!figures[name]) fail(file, `unknown figure ${name}`);
        blocks.push({ fig: figures[name] });
      } else {
        if (/^(#|>|\[)/.test(b)) fail(file, `unrecognised block: ${b.slice(0, 40)}`);
        blocks.push(b.replace(/\n/g, " "));
      }
    });
    blocks.forEach((b) => {
      const t = typeof b === "string" ? b : b.text || (b.ul || []).join(" ");
      words += t.split(/\s+/).length;
    });
    if (title === "Key ideas") { out.keyIdeas = blocks.flatMap((b) => b.ul || []); return; }
    if (title === "Further reading") { out.reading = blocks.flatMap((b) => b.ul || []); return; }
    out.sections.push({ id: out.id + "-s" + (out.sections.length + 1), title, blocks });
  });
  if (!out.keyIdeas.length) fail(file, "no Key ideas");
  out.words = words;
  out.minutes = Math.max(1, Math.round(words / WPM));
  return out;
}

const files = fs.readdirSync(dir).filter((f) => /^t\d+-.*\.txt$/.test(f)).sort();
const chapters = files.map(chapter);
const ids = new Set();
chapters.forEach((c, i) => {
  if (ids.has(c.id)) throw new Error(`duplicate chapter id ${c.id}`);
  ids.add(c.id);
  c.n = i + 1;
  if (!parts.some((p) => p.n === c.part)) throw new Error(`${c.id}: no part ${c.part}`);
});

const data = { parts, chapters };
const block = "/* THEORY:BEGIN — generated by theory/build.mjs from theory/*.txt; edit those, not this. */\n"
  + "PMP.THEORY = Object.freeze(" + JSON.stringify(data, null, 1) + ");\n/* THEORY:END */";

const src = fs.readFileSync(html, "utf8");
const a = src.indexOf("/* THEORY:BEGIN"), b = src.indexOf("/* THEORY:END */");
if (a < 0 || b < 0) throw new Error("index.html has no THEORY markers");
const next = src.slice(0, a) + block + src.slice(b + "/* THEORY:END */".length);
if (process.argv.includes("--check")) {
  if (next !== src) { console.error("index.html is out of date: run node theory/build.mjs"); process.exit(1); }
  console.log("PMP.THEORY is up to date.");
} else {
  fs.writeFileSync(html, next);
  console.log(`PMP.THEORY: ${chapters.length} chapters, ${chapters.reduce((s, c) => s + c.words, 0)} words.`);
}
